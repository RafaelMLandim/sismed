export const docsOfPhase = (phase: DocPhase) =>
  DOC_KEYS.filter((k) => DOC_META[k].phase === phase)

const docs = (
  overrides: Partial<Record<DocKey, DocStatus | IDocState>> = {},
): Record<DocKey, IDocState> =>
  Object.fromEntries(
    DOC_KEYS.map((k) => {
      const o = overrides[k]
      const state: IDocState =
        o === undefined
          ? { status: "nao_iniciado" }
          : typeof o === "string"
            ? { status: o }
            : o
      return [k, state]
    }),
  ) as Record<DocKey, IDocState>

