import { TODAY_ISO, addDays } from "./days"
import type { IVitalSign } from "./types"

const YESTERDAY = addDays(TODAY_ISO, -1)
const TWO_DAYS_AGO = addDays(TODAY_ISO, -2)

type Row = [
  date: string,
  time: string,
  sys: number,
  dia: number,
  hr: number,
  rr: number,
  temp: number,
  spo2: number,
  pain: number,
  by: string,
  extra?: Partial<IVitalSign>,
]

const rows = (patientId: string, list: Row[]): IVitalSign[] =>
  list.map(
    ([date, time, sys, dia, hr, rr, temp, spo2, pain, by, extra], i) => ({
      id: `v-${patientId}-${i}`,
      patientId,
      date,
      time,
      sys,
      dia,
      hr,
      rr,
      temp,
      spo2,
      pain,
      by,
      ...extra,
    }),
  )

